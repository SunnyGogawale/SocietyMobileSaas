export const API_PREFIX = '/api/v1'

export const ROLES = Object.freeze({
  SUPER_ADMIN: 'SUPER_ADMIN',
  SOCIETY_ADMIN: 'SOCIETY_ADMIN',
  SOCIETY_MANAGER: 'SOCIETY_MANAGER',
  COMMITTEE_MEMBER: 'COMMITTEE_MEMBER',
  ACCOUNTANT: 'ACCOUNTANT',
  SECURITY_GUARD: 'SECURITY_GUARD',
  MAINTENANCE_STAFF: 'MAINTENANCE_STAFF',
  RESIDENT: 'RESIDENT',
  TENANT: 'TENANT',
  VENDOR: 'VENDOR',
})

export const PERMISSIONS = Object.freeze({
  PLATFORM_MANAGE: 'platform:manage',
  RESIDENTS_READ: 'residents:read',
  RESIDENTS_WRITE: 'residents:write',
  FINANCE_READ: 'finance:read',
  FINANCE_WRITE: 'finance:write',
  COMPLAINTS_READ: 'complaints:read',
  COMPLAINTS_WRITE: 'complaints:write',
  VISITORS_READ: 'visitors:read',
  VISITORS_WRITE: 'visitors:write',
  DOCUMENTS_READ: 'documents:read',
  INVITATIONS_WRITE: 'invitations:write',
})

export const ROLE_PERMISSIONS = Object.freeze({
  [ROLES.SUPER_ADMIN]: Object.values(PERMISSIONS),
  [ROLES.SOCIETY_ADMIN]: Object.values(PERMISSIONS).filter((permission) => permission !== PERMISSIONS.PLATFORM_MANAGE),
  [ROLES.SOCIETY_MANAGER]: [
    PERMISSIONS.RESIDENTS_READ,
    PERMISSIONS.RESIDENTS_WRITE,
    PERMISSIONS.COMPLAINTS_READ,
    PERMISSIONS.COMPLAINTS_WRITE,
    PERMISSIONS.VISITORS_READ,
    PERMISSIONS.VISITORS_WRITE,
    PERMISSIONS.DOCUMENTS_READ,
    PERMISSIONS.INVITATIONS_WRITE,
  ],
  [ROLES.COMMITTEE_MEMBER]: [
    PERMISSIONS.RESIDENTS_READ,
    PERMISSIONS.COMPLAINTS_READ,
    PERMISSIONS.VISITORS_READ,
    PERMISSIONS.DOCUMENTS_READ,
  ],
  [ROLES.ACCOUNTANT]: [PERMISSIONS.FINANCE_READ, PERMISSIONS.FINANCE_WRITE, PERMISSIONS.DOCUMENTS_READ],
  [ROLES.SECURITY_GUARD]: [PERMISSIONS.VISITORS_READ, PERMISSIONS.VISITORS_WRITE],
  [ROLES.MAINTENANCE_STAFF]: [PERMISSIONS.COMPLAINTS_READ, PERMISSIONS.COMPLAINTS_WRITE],
  [ROLES.RESIDENT]: [PERMISSIONS.COMPLAINTS_READ, PERMISSIONS.COMPLAINTS_WRITE, PERMISSIONS.DOCUMENTS_READ],
  [ROLES.TENANT]: [PERMISSIONS.COMPLAINTS_READ, PERMISSIONS.COMPLAINTS_WRITE, PERMISSIONS.DOCUMENTS_READ],
  [ROLES.VENDOR]: [PERMISSIONS.COMPLAINTS_READ],
})

export function roleHasPermission(role, permission) {
  return ROLE_PERMISSIONS[role]?.includes(permission) ?? false
}